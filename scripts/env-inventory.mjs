#!/usr/bin/env node
/**
 * Inventory of every environment variable the server reads, generated from source.
 *
 *   docs/runbooks/env-inventory.md ← packages/server/src (tests excluded), cross-referenced with EVOLUTION_FLAGS
 *                                     (services/evolution-evidence.ts) and the runbook flag tables.
 *
 * `node scripts/env-inventory.mjs` writes the file; `--check` writes nothing and exits 1 when it is stale, so a new
 * `process.env.X` read cannot land without showing up here. Deterministic (no clock, sorted).
 *
 * ponytail: regex scan, not a TypeScript parse. It sees `process.env.X`, `env.X`, `env['X']` and `getEnv*('X')`; a name
 * built at runtime (`env[prefix + key]`) or destructured (`const { X } = process.env`) is not listed. Switch to the
 * compiler API if such reads become common.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SERVER_SRC = 'packages/server/src';
const FLAGS_FILE = `${SERVER_SRC}/services/evolution-evidence.ts`;
const RUNBOOK = 'docs/runbooks/self-improvement-loop-operations.md';
export const OUT = 'docs/runbooks/env-inventory.md';

const READ = /(?:\benv(?:\.|\[\s*['"])|\bgetEnv(?:Int|List)?\(\s*['"])([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+|[A-Z]{3,})\b/g;

function sourceFiles(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!['__tests__', 'node_modules', 'dist'].includes(e.name)) sourceFiles(p, out); }
    else if (/\.ts$/.test(e.name) && !/\.(test|spec|d)\.ts$/.test(e.name)) out.push(p);
  }
  return out;
}

/** name → sorted list of files (relative to the server source root) that read it. */
export function scanEnv(root = ROOT) {
  const base = path.join(root, SERVER_SRC);
  const reads = new Map();
  for (const file of sourceFiles(base)) {
    const rel = path.relative(base, file).split(path.sep).join('/');
    for (const m of fs.readFileSync(file, 'utf8').matchAll(READ)) {
      if (!reads.has(m[1])) reads.set(m[1], new Set());
      reads.get(m[1]).add(rel);
    }
  }
  return new Map([...reads].sort(([a], [b]) => (a < b ? -1 : 1)).map(([k, v]) => [k, [...v].sort()]));
}

function readOr(root, rel) {
  try { return fs.readFileSync(path.join(root, rel), 'utf8'); } catch { return ''; }
}

export function render(root = ROOT) {
  const reads = scanEnv(root);
  const registry = new Set([...readOr(root, FLAGS_FILE).matchAll(/name:\s*'([A-Z0-9_]+)'/g)].map((m) => m[1]));
  const runbook = new Set([...readOr(root, RUNBOOK).matchAll(/^\|\s*`([A-Z0-9_]+)`/gm)].map((m) => m[1]));
  const neither = [...reads.keys()].filter((n) => !registry.has(n) && !runbook.has(n));
  const L = [
    '<!-- Generated by scripts/env-inventory.mjs. Do not edit; run `node scripts/env-inventory.mjs`. -->',
    '',
    '# Environment variable inventory',
    '',
    `Every environment variable read in \`${SERVER_SRC}\` (tests excluded), from a source scan.`,
    `Registry = listed in \`EVOLUTION_FLAGS\` (\`${FLAGS_FILE}\`). Runbook = has a row in a flag table of \`${RUNBOOK}\`.`,
    'A variable in neither is not wrong, but nothing else in the repository tells an operator that it exists.',
    '',
    `- Read by the server: ${reads.size}`,
    `- In the registry: ${[...reads.keys()].filter((n) => registry.has(n)).length}`,
    `- In the runbook: ${[...reads.keys()].filter((n) => runbook.has(n)).length}`,
    `- In neither: ${neither.length}`,
    '',
    '| Variable | Registry | Runbook | Read in |',
    '|---|---|---|---|',
  ];
  for (const [name, files] of reads) {
    const where = files.slice(0, 2).map((f) => `\`${f}\``).join(', ') + (files.length > 2 ? ` +${files.length - 2}` : '');
    L.push(`| \`${name}\` | ${registry.has(name) ? 'yes' : 'no'} | ${runbook.has(name) ? 'yes' : 'no'} | ${where} |`);
  }
  return L.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const unknown = process.argv.slice(2).filter((a) => a !== '--check');
  if (unknown.length) { console.error(`unknown argument: ${unknown.join(' ')}`); process.exit(2); }
  const want = render();
  if (process.argv.includes('--check')) {
    if (readOr(ROOT, OUT) !== want) {
      console.error(`${OUT} is stale: run \`node scripts/env-inventory.mjs\` and commit the result.`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(path.join(ROOT, OUT), want);
  }
}
